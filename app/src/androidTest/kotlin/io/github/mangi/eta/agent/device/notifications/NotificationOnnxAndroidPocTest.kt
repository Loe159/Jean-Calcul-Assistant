package io.github.mangi.eta.agent.device.notifications

import ai.onnxruntime.OnnxTensor
import ai.onnxruntime.OrtEnvironment
import ai.onnxruntime.OrtSession
import android.os.Debug
import android.os.SystemClock
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import java.io.File
import java.security.MessageDigest
import java.nio.LongBuffer
import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Test
import org.junit.runner.RunWith

/**
 * Phase-A-only instrumentation test. Synthetic input IDs are generated by the
 * pinned HF BPE tokenizer on the host. Real notification bodies are NEVER read.
 *
 * The ONNX file is not shipped in the APK. Stage it explicitly at
 * /sdcard/Android/data/fr.loevan.jeancalcul.v2/files/notification-model/model_quantized.onnx
 * before invoking this test. The test is SKIPPED if it isn't present.
 */
@RunWith(AndroidJUnit4::class)
class NotificationOnnxAndroidPocTest {
    @Test
    fun pinnedOnnxRunsOnAndroidWithReferenceInputs() {
        val instrumentation = InstrumentationRegistry.getInstrumentation()
        val context = instrumentation.targetContext
        val model = File(context.getExternalFilesDir(null), "notification-model/model_quantized.onnx")
        assumeTrue("Model is not installed: $model", model.exists())
        val fixtures = JSONObject(
            instrumentation.context.assets.open("notification_nli_reference.json")
                .bufferedReader().use { it.readText() },
        )
        assertEquals("17af5f8a728d101ce33a9bffad227b0cd005e95e", fixtures.getString("revision"))
        val digest = MessageDigest.getInstance("SHA-256")
        model.inputStream().buffered().use { stream ->
            val buffer = ByteArray(1024 * 1024)
            while (true) {
                val n = stream.read(buffer)
                if (n < 0) break
                digest.update(buffer, 0, n)
            }
        }
        val sha = digest.digest().joinToString("") { "%02x".format(it) }
        assertEquals(fixtures.getString("model_sha256"), sha)
        val options = OrtSession.SessionOptions().apply {
            setIntraOpNumThreads(2)
            setInterOpNumThreads(1)
            setExecutionMode(OrtSession.SessionOptions.ExecutionMode.SEQUENTIAL)
            addConfigEntry("session.intra_op.allow_spinning", "0")
            addConfigEntry("session.inter_op.allow_spinning", "0")
        }
        val environment = OrtEnvironment.getEnvironment()
        val beforePss = Debug.getPss()
        val loadStart = SystemClock.elapsedRealtimeNanos()
        environment.createSession(model.absolutePath, options).use { session ->
            val sessionLoadMs = (SystemClock.elapsedRealtimeNanos() - loadStart) / 1_000_000.0
            assertEquals(setOf("input_ids", "attention_mask"), session.inputNames)
            assertEquals(setOf("logits"), session.outputNames)
            val cases = fixtures.getJSONArray("cases")
            var worstDifference = 0.0
            val timings = mutableListOf<Double>()
            for (caseNumber in 0 until cases.length()) {
                val fixture = cases.getJSONObject(caseNumber)
                val idRows = fixture.getJSONArray("input_ids")
                val maskRows = fixture.getJSONArray("attention_mask")
                val batch = idRows.length()
                val sequence = idRows.getJSONArray(0).length()
                val ids = LongArray(batch * sequence)
                val masks = LongArray(batch * sequence)
                for (row in 0 until batch) {
                    assertEquals(sequence, idRows.getJSONArray(row).length())
                    assertEquals(sequence, maskRows.getJSONArray(row).length())
                    for (column in 0 until sequence) {
                        ids[row * sequence + column] = idRows.getJSONArray(row).getLong(column)
                        masks[row * sequence + column] = maskRows.getJSONArray(row).getLong(column)
                    }
                }
                OnnxTensor.createTensor(environment, LongBuffer.wrap(ids), longArrayOf(batch.toLong(), sequence.toLong())).use { tokens ->
                    OnnxTensor.createTensor(environment, LongBuffer.wrap(masks), longArrayOf(batch.toLong(), sequence.toLong())).use { attention ->
                        val start = SystemClock.elapsedRealtimeNanos()
                        session.run(mapOf("input_ids" to tokens, "attention_mask" to attention)).use { result ->
                            timings += (SystemClock.elapsedRealtimeNanos() - start) / 1_000_000.0
                            val logits = result[0].value as Array<*>
                            val expected = fixture.getJSONArray("logits")
                            assertEquals(batch, logits.size)
                            for (row in 0 until batch) {
                                val actual = logits[row] as FloatArray
                                assertEquals(2, actual.size)
                                for (column in 0..1) {
                                    val delta = kotlin.math.abs(actual[column] - expected.getJSONArray(row).getDouble(column))
                                    worstDifference = maxOf(worstDifference, delta)
                                }
                            }
                        }
                    }
                }
            }
            assertTrue("Logit delta too large: $worstDifference", worstDifference <= 0.05)
            val timingsSorted = timings.sorted()
            // No private contents in the diagnostic: only timing and RAM.
            println("NOTIFICATION_ONNX_ANDROID_POC session_load_ms=$sessionLoadMs " +
                "p50_ms=${timingsSorted[timingsSorted.size / 2]} " +
                "p95_ms=${timingsSorted[(timingsSorted.size * 95 / 100).coerceAtMost(timingsSorted.lastIndex)]} " +
                "pss_delta_kib=${Debug.getPss() - beforePss} max_logit_delta=$worstDifference")
        }
        options.close()
    }
}
