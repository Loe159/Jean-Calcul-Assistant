#!/usr/bin/env python3
"""Visual assessment for disposable emulator screenshots only; never send user data."""
import argparse
import json
import os
from pathlib import Path
import re
import sys
import urllib.error
import urllib.request
import base64

from PIL import Image, ImageChops, ImageStat

ROOT = Path(__file__).resolve().parent
ALLOWED = re.compile(r"^[0-9]{2}-[a-z-]+[.]png$")
VALID = {"PASS", "FAIL", "NOT_RUN"}


def visual_difference(actual, baseline, tolerance=0.025):
    """Fraction of RGB channels whose difference exceeds 20/255."""
    with Image.open(actual) as current, Image.open(baseline) as reference:
        current = current.convert("RGB")
        reference = reference.convert("RGB")
        if current.size != reference.size:
            return 1.0
        delta = ImageChops.difference(current, reference)
        histogram = delta.histogram()
        changed = sum(histogram[channel * 256 + value]
                      for channel in range(3) for value in range(21, 256))
        score = changed / (current.width * current.height * 3)
        return score


def vision_review(image, criterion, key, model):
    # Only exact allowlisted screenshots generated by CI on an empty emulator.
    if os.getenv("GITHUB_ACTIONS") != "true" or os.getenv("E2E_SYNTHETIC_ONLY") != "true":
        raise RuntimeError("Vision uploads require an isolated CI emulator and fake data")
    if not ALLOWED.fullmatch(image.name):
        raise RuntimeError("Screenshot name rejected")
    if image.stat().st_size > 3_000_000:
        raise RuntimeError("Screenshot too large")
    payload = {
        "model": model,
        "temperature": 0,
        "response_format": {"type": "json_object"},
        "messages": [
            {"role": "system", "content": (
                "You review synthetic Android app screenshots. Return JSON keys "
                "status (PASS or FAIL), rationale (short), issues (array). "
                "Judge only visible evidence, never invent behavior or claim parity "
                "with an unseen reference. If uncertain, FAIL and explain."
            )},
            {"role": "user", "content": [
                {"type": "text", "text": "Criterion: " + criterion["id"] + ". " +
                 criterion["description"] + ". Report actual visible defects."},
                {"type": "image_url", "image_url": {"url":
                    "data:image/png;base64," + base64.b64encode(image.read_bytes()).decode("ascii")}}
            ]}
        ]
    }
    request = urllib.request.Request(
        "https://api.openai.com/v1/chat/completions",
        data=json.dumps(payload).encode(),
        headers={"Authorization": "Bearer " + key, "Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(request, timeout=50) as reply:
        body = json.load(reply)
    answer = json.loads(body["choices"][0]["message"]["content"])
    if answer.get("status") not in {"PASS", "FAIL"}:
        raise ValueError("Invalid vision verdict")
    return {
        "status": answer["status"],
        "rationale": str(answer.get("rationale", ""))[:400],
        "issues": [str(item)[:180] for item in answer.get("issues", [])[:8]],
    }


def aggregate(statuses):
    if "FAIL" in statuses:
        return "FAIL"
    if "NOT_RUN" in statuses or not statuses:
        return "NOT_RUN"
    return "PASS"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--captures", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--instrumentation", choices=sorted(VALID), default="NOT_RUN")
    parser.add_argument("--baselines", type=Path, default=ROOT / "baselines")
    parser.add_argument("--fixture-defect", action="store_true",
                        help="Only for synthetic unit-test screenshots")
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    checklist = json.loads((ROOT / "visual-criteria.json").read_text())
    key = os.getenv("OPENAI_API_KEY", "")
    model = os.getenv("E2E_VISION_MODEL", "gpt-4.1-mini")
    results = []
    for criterion in checklist["criteria"]:
        shots = criterion["captures"]
        exists = [args.captures / name for name in shots]
        missing = [p.name for p in exists if not p.is_file()]
        checks = []
        notes = []
        if criterion["id"] == "stability.instrumentation":
            checks.append(args.instrumentation)
            notes.append("Instrumented Android test result: " + args.instrumentation)
        elif missing:
            checks.append("FAIL" if args.instrumentation == "PASS" else "NOT_RUN")
            notes.append("Missing screenshots: " + ", ".join(missing))
        else:
            for shot in exists:
                if not ALLOWED.fullmatch(shot.name):
                    checks.append("FAIL")
                    notes.append("Unsafe screenshot filename")
                    continue
                try:
                    with Image.open(shot) as im:
                        im.verify()
                    with Image.open(shot) as im:
                        if im.width < 300 or im.height < 500:
                            checks.append("FAIL")
                            notes.append("Invalid dimensions: " + shot.name)
                except (OSError, ValueError):
                    checks.append("FAIL")
                    notes.append("Unreadable PNG: " + shot.name)
                    continue
                baseline = args.baselines / shot.name
                if baseline.exists():
                    score = visual_difference(shot, baseline)
                    verdict = "FAIL" if score > 0.025 else "PASS"
                    checks.append(verdict)
                    notes.append(f"Baseline {shot.name}: changed={score:.3%} ({verdict})")
                else:
                    checks.append("NOT_RUN")
                    notes.append("No approved pixel baseline for " + shot.name)
                if key:
                    try:
                        review = vision_review(shot, criterion, key, model)
                        checks.append(review["status"])
                        notes.append("Vision " + shot.name + ": " + review["rationale"])
                        notes.extend(review["issues"])
                    except Exception as exc:
                        checks.append("NOT_RUN")
                        notes.append("Vision unavailable (" + type(exc).__name__ + ")")
                else:
                    checks.append("NOT_RUN")
                    notes.append("Vision not configured (OPENAI_API_KEY absent)")
        if criterion["type"] == "functional" and not missing:
            # Instrumentation asserts functional behaviour; screenshots alone do not.
            checks = [args.instrumentation]
            notes.append("Functional outcome comes from instrumentation assertions")
        result = {"id": criterion["id"], "type": criterion["type"],
                  "status": aggregate(checks), "evidence": shots,
                  "notes": notes}
        results.append(result)
    summary = {status: sum(x["status"] == status for x in results) for status in sorted(VALID)}
    report = {"schema_version": 1, "instrumentation": args.instrumentation,
              "vision_executed": bool(key and os.getenv("E2E_SYNTHETIC_ONLY") == "true"
                                      and os.getenv("GITHUB_ACTIONS") == "true"),
              "model": model if key else None, "summary": summary, "criteria": results}
    (args.out / "report.json").write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n")
    lines = ["# E2E Android report", "",
             f"Instrumentation: **{args.instrumentation}**. "
             f"PASS: {summary['PASS']}; FAIL: {summary['FAIL']}; NOT_RUN: {summary['NOT_RUN']}.",
             "", "| Criterion | Type | Result |", "|---|---|---|"]
    lines.extend(f"| {x['id']} | {x['type']} | **{x['status']}** |" for x in results)
    lines.extend(["", "## Evidence / limitations", ""])
    for result in results:
        lines.append("### " + result["id"])
        lines.extend("- " + re.sub(r"(?i)(sk-[a-z0-9_-]+)", "[REDACTED]", note)
                     for note in result["notes"])
    (args.out / "report.md").write_text("\n".join(lines) + "\n")
    print(json.dumps({"summary": summary, "report": str(args.out / "report.json")}))
    # Visual criteria without baselines or vision remain NOT_RUN (not CI failures).
    # Missing screenshots or explicitly detected visual regressions are failures.
    return 1 if summary["FAIL"] else 0


if __name__ == "__main__":
    sys.exit(main())
